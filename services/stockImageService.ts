// Local storage key for historical photos
const STORAGE_USED_UNSPLASH_KEY = 'jongiyoh_unsplash_used_photos_v1';

export const getUsedUnsplashIds = (): Set<string> => {
  try {
    const raw = localStorage.getItem(STORAGE_USED_UNSPLASH_KEY);
    if (raw) {
      const arr = JSON.parse(raw);
      if (Array.isArray(arr)) return new Set(arr);
    }
  } catch (e) {}
  return new Set<string>();
};

export const markUnsplashIdUsed = (id: string): void => {
  if (!id) return;
  try {
    const current = getUsedUnsplashIds();
    current.add(id);
    const trimmed = Array.from(current).slice(-200);
    localStorage.setItem(STORAGE_USED_UNSPLASH_KEY, JSON.stringify(trimmed));
  } catch (e) {}
};

export const resetUsedUnsplashHistory = (): void => {
  try {
    localStorage.removeItem(STORAGE_USED_UNSPLASH_KEY);
  } catch (e) {}
};

export const extractUnsplashPhotoId = (url: string): string | null => {
  if (!url || !url.includes('images.unsplash.com')) return null;
  const match = url.match(/photo-([a-zA-Z0-9_-]+)/);
  return match ? `photo-${match[1]}` : null;
};

export const buildUnsplashVerticalUrl = (photoId: string): string => {
  return `https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=1080&h=1920&q=85`;
};

export const getAllPhotoIds = (): string[] => {
  const all: string[] = [];
  Object.values(UNSPASH_TOPIC_COLLECTIONS).forEach(arr => {
    arr.forEach(id => {
      if (!all.includes(id)) all.push(id);
    });
  });
  return all;
};

/**
 * Detects best fitting category based on the text/keywords of the scene
 */
const detectTargetCategory = (text: string, sceneIndex: number): string => {
  const t = text.toLowerCase();

  // 1. Kurkumin, kurkuma, piperin, zarchava, zanjabil
  if (/kurkumin|kurkuma|piperin|zarchava|zanjabil|asal|sariq|polifenol/i.test(t)) {
    return 'turmeric_curcumin_spices';
  }

  // 2. Damlama, damlash, choy, choynak, qaynoq suv, tindirish, ichish, stakan
  if (/damla|choynak|piyola|stakan|tindir|suv hammomi|ichiladi|ertalab|qaynoq/i.test(t)) {
    return 'brewing_tea_apothecary';
  }

  // 3. Bo'g'im, harakat, tizza, qisirlash, suyak, artroz, yurish, gimnastika, yengillik
  if (/bo['`‘]g['`‘]im|tizza|qisir|artroz|harakat|gimnastika|suyak|yurish|yengil/i.test(t)) {
    return 'joints_healthy_movement';
  }

  // 4. Qarshi ko'rsatma, xavfsizlik, dori, shifokor, homiladorlik, buyrak, maslahat, manba, ibn sino
  if (/qarshi|mumkin emas|taqiq|xavf|buyrak|homilador|dori|vrach|shifokor|ibn sino|manba|disclaimer/i.test(t)) {
    return 'safety_consultation_books';
  }

  // 5. Tog', tabiat, kiyiko'ti, kovul, qirqbo'g'in, toza havo, o'zbekiston
  if (/tog['`‘]|kovul|kiyiko['`‘]ti|zizifora|shudring|dala|tabiat|vodiy/i.test(t)) {
    return 'mountain_nature_central_asia';
  }

  // 6. Call to Action / Telegram / Obuna
  if (/bot|telegram|obuna|saqlab|jongiyoh|kanal|doza|ulashing/i.test(t)) {
    return 'mobile_social_cta';
  }

  // 7. Giyohlar va botanika
  if (/qirqbo['`‘]g['`‘]in|giyoh|o['`‘]t|dorivor|o['`‘]simlik|ildiz|barg/i.test(t)) {
    return 'medicinal_herbs_botanical';
  }

  // Fallback category rotation based on scene index
  const categories = Object.keys(UNSPASH_TOPIC_COLLECTIONS);
  return categories[sceneIndex % categories.length] || 'medicinal_herbs_botanical';
};

/**
 * Selects an authentic Unsplash photo that:
 * 1. Has NEVER been used in previous posts (stored in localStorage)
 * 2. Has NOT been used in the current post/batch (excludedIds)
 * 3. Contextually matches the phytotherapy topic
 */
export const resolveContextualStockImage = (
  keyword: string = '',
  articleContext: string = '',
  sceneIndex: number = 0,
  excludedIds: Set<string> = new Set()
): string => {
  const combined = `${keyword} ${articleContext}`;
  const targetCategory = detectTargetCategory(combined, sceneIndex);
  
  const usedHistory = getUsedUnsplashIds();
  const isForbidden = (id: string): boolean => {
    return excludedIds.has(id) || usedHistory.has(id);
  };

  const categoryPhotos = UNSPASH_TOPIC_COLLECTIONS[targetCategory] || UNSPASH_TOPIC_COLLECTIONS.medicinal_herbs_botanical;

  // 1. Try to find an unused photo in the exact target category
  const availableInCategory = categoryPhotos.filter(id => !isForbidden(id));
  let chosenId: string | null = null;

  if (availableInCategory.length > 0) {
    chosenId = availableInCategory[Math.floor(Math.random() * availableInCategory.length)];
  } else {
    // 2. Search related categories
    const allPhotos = getAllPhotoIds();
    const availableGlobally = allPhotos.filter(id => !isForbidden(id));

    if (availableGlobally.length > 0) {
      chosenId = availableGlobally[Math.floor(Math.random() * availableGlobally.length)];
    } else {
      // 3. Fallback to any not used in current post
      const allowedInCurrentPost = allPhotos.filter(id => !excludedIds.has(id));
      chosenId = allowedInCurrentPost[Math.floor(Math.random() * allowedInCurrentPost.length)] || allPhotos[0];
    }
  }

  if (chosenId) {
    markUnsplashIdUsed(chosenId);
    excludedIds.add(chosenId);
  }

  return buildUnsplashVerticalUrl(chosenId || categoryPhotos[0]);
};

/**
 * Selects an alternative stock photo guaranteed not to match the current photo.
 */
export const getRandomStockImageForScene = (
  topicHint: string = '',
  currentUrl?: string,
  excludedInProject: Set<string> = new Set()
): string => {
  const currentId = currentUrl ? extractUnsplashPhotoId(currentUrl) : null;
  const usedHistory = getUsedUnsplashIds();
  const allPhotos = getAllPhotoIds();

  const isForbidden = (id: string): boolean => {
    if (currentId && id === currentId) return true;
    if (excludedInProject.has(id)) return true;
    if (usedHistory.has(id)) return true;
    return false;
  };

  const freshCandidates = allPhotos.filter(id => !isForbidden(id));

  let pickedId: string;
  if (freshCandidates.length > 0) {
    pickedId = freshCandidates[Math.floor(Math.random() * freshCandidates.length)];
  } else {
    const candidatesNotInProject = allPhotos.filter(id => id !== currentId && !excludedInProject.has(id));
    pickedId = candidatesNotInProject[Math.floor(Math.random() * candidatesNotInProject.length)] || allPhotos[0];
  }

  markUnsplashIdUsed(pickedId);
  excludedInProject.add(pickedId);
  return buildUnsplashVerticalUrl(pickedId);
};
